import type { ReactNode } from "react";

/**
 * حاجات المطوّر — بتظهر على localhost بس.
 *
 * ⚠️ الصفحة الرئيسية كانت بتعرض للزائر "المرحلة ٠ خلصت" وجدول بعدد
 * الحقول المؤكدة والتقديرية. دي معلومات **بتاعتنا إحنا**، مش بتاعته:
 * الزائر داخل يعرف فلوسه تكفيه كام شهر، مش يعرف إحنا وصلنا فين في
 * البناء ولا كام حقل لسه محتاج تأكيد.
 *
 * ⚠️ **مش بديل عن صفحة `/sources`.** الشفافية عن حالة الداتا وعد أساسي
 * في الموقع، وليها صفحتها اللي أي حد يقدر يفتحها. اللي اتشال هنا هو
 * تكرارها في وش الزائر على الصفحة الأولى.
 *
 * `NODE_ENV` بيبقى "development" مع `npm run dev` بس. أي build حقيقي —
 * محلي أو على Vercel — بيبقى "production"، فالمحتوى ده مش بيتحط في
 * الصفحة أصلًا مش بس بيتخفي بالCSS.
 */
export function DevOnly({ children }: { children: ReactNode }) {
  if (process.env.NODE_ENV !== "development") return null;
  return <>{children}</>;
}
